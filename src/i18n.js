const STR = { en, ta, hi };

export function makeT(lang) {
  return (key, vars) => {
    let s = (STR[lang] && STR[lang][key]) ?? en[key] ?? key;
    if (typeof s === 'string' && vars) {
      Object.keys(vars).forEach((k) => { s = s.split(`{${k}}`).join(String(vars[k])); });
    }
    return s;
  };
}
